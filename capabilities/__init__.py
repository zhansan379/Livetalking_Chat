#  可插拔能力包（capabilities/）
#
#  每个子包 = 一个「能力」（Capability）：多轮、有状态、自带 persona/业务逻辑的域。
#  与普通「工具」（TOOL_REGISTRY 里的 web_search/weather/list_files 等）的区分：
#     - 工具：通用、无状态、永远按配置可用；
#     - 能力：整域、有会话状态、按「状态」条件注入工具 + 注入 system_block。
#
#  约定（见 hub.py）：
#     - 每个能力子包导出 `CAPABILITY: base.Capability` 实例 + `config_defaults() -> dict`；
#     - 添加新能力 = 新建一个子包 + 导出上述两项，主循环无需改动。
###############################################################################